export function normalizeSet(data) {
  const items = Array.isArray(data) ? data : data?.poems;
  if (!Array.isArray(items) || !items.length) throw new Error('沒有找到籤詩');
  const poems = items.map((p, i) => ({
    n: Number(p.n) || i + 1,
    gz: p.gz || LABELS[i] || '',
    luck: LUCK_ORDER.includes(p.luck) ? p.luck : '中平',
    lines: (Array.isArray(p.lines) ? p.lines : String(p.poem || '').split(/[\n，。]/))
      .map(x => String(x).trim()).filter(Boolean).slice(0, 8),
    gist: p.gist || '',
  })).filter(p => p.lines.length);
  if (!poems.length) throw new Error('籤詩內容是空的');
  return {
    id: 'imported_' + Date.now().toString(36),
    name: data?.name || '匯入的籤詩集',
    source: data?.source || '使用者匯入',
    builtin: false,
    poems,
  };
}
