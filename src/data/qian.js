import { STEMS, BRANCHES } from '../engines/calendar.js';

/** 六十甲子籤的編號：陽干配陽支、陰干配陰支，每干六支 */
export function ganzhiLabels() {
  const yang = [0, 2, 4, 6, 8, 10];   // 子寅辰午申戌
  const yin = [1, 3, 5, 7, 9, 11];    // 丑卯巳未酉亥
  const out = [];
  for (let s = 0; s < 10; s++) {
    const slots = s % 2 === 0 ? yang : yin;
    for (const b of slots) out.push(STEMS[s] + BRANCHES[b]);
  }
  return out;
}

